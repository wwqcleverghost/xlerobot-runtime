@dataclass
class DatasetRecordConfig:
    # Dataset identifier. By convention it should match '{hf_username}/{dataset_name}' (e.g. `lerobot/test`).
    repo_id: str
    # A short but accurate description of the task performed during the recording (e.g. "Pick the Lego block and drop it in the box on the right.")
    single_task: str
    # Root directory where the dataset will be stored (e.g. 'dataset/path').
    root: str | Path | None = None
    # Limit the frames per second.
    fps: int = 30
    # Number of seconds for data recording for each episode.
    episode_time_s: int | float = 60
    # Number of seconds for resetting the environment after each episode.
    reset_time_s: int | float = 60
    # Target total episodes, including episodes already saved when resuming.
    num_episodes: int = 50
    # Encode frames in the dataset into video
    video: bool = True
    # Upload dataset to Hugging Face hub.
    push_to_hub: bool = False
    # Upload on private repository on the Hugging Face hub.
    private: bool = False
    # Add tags to your dataset on the hub.
    tags: list[str] | None = None
    # Number of subprocesses handling the saving of frames as PNG. Set to 0 to use threads only;
    # set to ≥1 to use subprocesses, each using threads to write images. The best number of processes
    # and threads depends on your system. We recommend 4 threads per camera with 0 processes.
    # If fps is unstable, adjust the thread count. If still unstable, try using 1 or more subprocesses.
    num_image_writer_processes: int = 0
    # Number of threads writing the frames as png images on disk, per camera.
    # Too many threads might cause unstable teleoperation fps due to main thread being blocked.
    # Not enough threads might cause low camera fps.
    num_image_writer_threads_per_camera: int = 4
    # Number of episodes to record before batch encoding videos
    # Set to 1 for immediate encoding (default behavior), or higher for batched encoding
    video_encoding_batch_size: int = 1
    # Rename map for the observation to override the image and state keys
    rename_map: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        if self.single_task is None:
            raise ValueError("You need to provide a task as argument in `single_task`.")


@dataclass
class RecordConfig:
    robot: RobotConfig
    dataset: DatasetRecordConfig
    # Whether to control the robot with a teleoperator
    teleop: TeleoperatorConfig | None = None
    # Whether to control the robot with a policy
    policy: PreTrainedConfig | None = None
    # Display all cameras on screen
    display_data: bool = False
    # Use vocal synthesis to read events.
    play_sounds: bool = True
    # Resume recording on an existing dataset.
    resume: bool = False
    # [eval] Dataset whose median first frame is the reset pose (default: from the policy's train_config.json).
    reset_dataset: str | None = None
    # [eval] Arm reset speed, joint units per second.
    reset_speed: float = 40.0
    # [eval] Per-frame limit on each .pos joint command for policy actions, with an EMA (alpha 0.8), same as
    # the recording script's smooth_arm_action. Prevents jumps at action-chunk boundaries. 0 disables.
    max_arm_step: float = 3.0
    # Keep the mobile base still during policy evaluation unless explicitly enabled.
    allow_base: bool = False
    # [eval] With a policy and a leader teleop: space toggles a human takeover mid-episode. On takeover the
    # leader is driven to the follower's pose first, so control switches without a jump. Takeover frame
    # ranges go to interventions.csv next to success.csv.
    takeover: bool = False

    def __post_init__(self):
        # HACK: We parse again the cli args here to get the pretrained path if there was one.
        policy_path = parser.get_path_arg("policy")
        if policy_path:
            cli_overrides = parser.get_cli_overrides("policy")
            self.policy = PreTrainedConfig.from_pretrained(policy_path, cli_overrides=cli_overrides)
            self.policy.pretrained_path = policy_path

        if self.teleop is None and self.policy is None:
            raise ValueError("Choose a policy, a teleoperator or both to control the robot")

    @classmethod
    def __get_path_fields__(cls) -> list[str]:
        """This enables the parser to load config from the policy using `--policy.path=local/dir`"""
        return ["policy"]


""" --------------- record_loop() data flow --------------------------
       [ Robot ]
           V
     [ robot.get_observation() ] ---> raw_obs
           V
     [ robot_observation_processor ] ---> processed_obs
           V
     .-----( ACTION LOGIC )------------------.
     V                                       V
     [ From Teleoperator ]                   [ From Policy ]
     |                                       |
     |  [teleop.get_action] -> raw_action    |   [predict_action]
     |          |                            |          |
     |          V                            |          V
     | [teleop_action_processor]             |          |
     |          |                            |          |
     '---> processed_teleop_action           '---> processed_policy_action
     |                                       |
     '-------------------------.-------------'
                               V
                  [ robot_action_processor ] --> robot_action_to_send
                               V
                    [ robot.send_action() ] -- (Robot Executes)
                               V
                    ( Save to Dataset )
                               V
                  ( Rerun Log / Loop Wait )
"""


@safe_stop_image_writer
def record_loop(
    robot: Robot,
    events: dict,
    fps: int,
    teleop_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs after teleop
    robot_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs before robot
    robot_observation_processor: RobotProcessorPipeline[
        RobotObservation, RobotObservation
    ],  # runs after robot
    dataset: LeRobotDataset | None = None,
    teleop: Teleoperator | list[Teleoperator] | None = None,
    policy: PreTrainedPolicy | None = None,
    preprocessor: PolicyProcessorPipeline[dict[str, Any], dict[str, Any]] | None = None,
    postprocessor: PolicyProcessorPipeline[PolicyAction, PolicyAction] | None = None,
    control_time_s: int | None = None,
    single_task: str | None = None,
    display_data: bool = False,
    max_arm_step: float = 0.0,
    allow_base: bool = False,
    takeover: bool = False,
    leader_rest: dict | None = None,
) -> list[tuple[int, int]]:
    """Returns the [start, end) frame ranges of this episode that were recorded under human takeover."""
    if dataset is not None and dataset.fps != fps:
        raise ValueError(f"The dataset fps should be equal to requested fps ({dataset.fps} != {fps}).")

    teleop_arm = teleop_keyboard = None
    if isinstance(teleop, list):
        teleop_keyboard = next((t for t in teleop if isinstance(t, KeyboardTeleop)), None)
        teleop_arm = next(
            (
                t
                for t in teleop
                if isinstance(
                    t,
                    (
                        so100_leader.SO100Leader
                        | so101_leader.SO101Leader
                        | koch_leader.KochLeader
                        | omx_leader.OmxLeader
                    ),
                )
            ),
            None,
        )

        if not (teleop_arm and teleop_keyboard and len(teleop) == 2 and robot.name == "lekiwi_client"):
            raise ValueError(
                "For multi-teleop, the list must contain exactly one KeyboardTeleop and one arm teleoperator. Currently only supported for LeKiwi robot."
            )

    # Reset policy and processor if they are provided
    if policy is not None and preprocessor is not None and postprocessor is not None:
        policy.reset()
        preprocessor.reset()
        postprocessor.reset()

    prev_sent = None  # [eval] last command sent, for max_arm_step smoothing
    # [eval] stage input: a policy trained with observation.environment_state (docs/workflows/stage-labels) gets the live
    # fine9 stage each frame; it is turned on by the policy's inputs, not by a flag, and is fed to the policy only (not recorded)
    stage = live_stage(policy)
    memory = isinstance(stage, ProgressMemory)  # [eval] progress feedback: the model keeps its own progress s
    last_cmd, stage_now, pred_stage = None, None, None
    # [eval] per-frame [frame, rule stage, model stage, prob, progress] of stage models, saved to stages.csv (save_stage_log)
    events["stage_log"] = log = []
    # [eval] STALL=<resample|rewind>:<seconds>: what to do when the arms hover in place (StallGuard, docs/workflows/v9)
    guard = StallGuard(os.environ["STALL"], fps) if policy is not None and os.environ.get("STALL") else None
    events["stall_log"] = guard.log if guard is not None else []
    guard_keys = [k for k in dataset.features[OBS_STATE]["names"] if "arm" in k] if guard is not None else []
    raw_hist = []  # [eval] previous two policy outputs, for smooth_arm_action
    state_range = train_state_range(preprocessor)
    events["takeover"] = False
    human = False  # [eval] the leader currently drives the robot
    offset = {}  # [eval] follower - leader pose at takeover, added to leader commands so nothing jumps
    blend_from, blend_frames = None, 0  # [eval] command at the last control switch, eased out over 1 s
    spans = []
    homing = None  # [eval] background thread sending the leader to `leader_rest` after a hand-back

    timestamp = 0
    start_episode_t = time.perf_counter()
    while timestamp < control_time_s:
        start_loop_t = time.perf_counter()

        if events["stop_recording"] or events["exit_early"]:
            events["exit_early"] = False
            break

        # Get robot observation
        obs = robot.get_observation()

        # Applies a pipeline to the raw robot observation, default is IdentityProcessor
        obs_processed = robot_observation_processor(obs)
        if stage is not None:  # [eval] every frame, takeover frames too, so the stage is current when the policy resumes
            prev_stage, stage_now = stage_now, stage(obs, last_cmd)
            if not memory and (prev_stage is None or prev_stage.argmax() != stage_now.argmax()):
                print(f"[stage] {timestamp:6.2f}s  {int(stage_now.argmax())}", flush=True)  # 0-8 = STAGES order

        if policy is not None or dataset is not None:
            observation_frame = build_dataset_frame(dataset.features, obs_processed, prefix=OBS_STR)

        if takeover and events["takeover"] != human:
            human = events["takeover"]
            frame = dataset.episode_buffer["size"] if dataset is not None else 0
            if human:
                if homing is not None:
                    homing.join()  # the leader bus is not shared between threads
                print("Takeover: the leader is moving to the robot pose, hold it lightly...")
                align_leader(teleop, obs, fps, stop=lambda: events["stop_recording"] or events["exit_early"])
                leader = teleop.get_action()
                # Grippers get no offset: they keep the usual teleop mapping (an offset would stop them closing fully).
                offset = {k: float(obs[k]) - float(v) for k, v in leader.items() if k in obs and "gripper" not in k}
                worst = max(offset, key=lambda k: abs(offset[k]))
                print(f"Leader-follower gap after alignment: max {offset[worst]:+.1f} at {worst} (compensated)")
                spans.append([frame, frame])
                print("Takeover: you have control. Space hands control back to the policy.")
            else:
                spans[-1][1] = frame
                policy.reset()  # replan from the current observation, not the pre-takeover plan
                preprocessor.reset()
                postprocessor.reset()
                if leader_rest is not None:  # the leader goes back to rest while the policy drives
                    homing = threading.Thread(
                        target=align_leader, args=(teleop, leader_rest, fps), kwargs={"show": False}
                    )
                    homing.start()
                print("Policy has control again.")
            raw_hist = []
            # Either way, the new source takes over gradually from the last command sent (no jump, no lurch).
            blend_from = {k: float(v) for k, v in (prev_sent or obs).items() if k.endswith(".pos")}
            blend_frames = 0
            continue  # alignment took time; start the next frame from a fresh observation

        # Get action from either policy or teleop
        pred_now, prob_now, prog_now = -1, float("nan"), float("nan")  # the model's own stage guess (-1: none / human frame)
        if human:
            leader = teleop.get_action()
            command = {k: v + offset.get(k, 0.0) for k, v in leader.items()}
            act_processed_teleop = teleop_action_processor((command, obs))
            act_processed_policy = None
        elif policy is not None and guard is not None and guard.queue:  # [eval] StallGuard rewind: the pre-stall commands, backwards
            act_processed_policy = dict(guard.queue.pop(0))
            if not guard.queue:  # back where the approach was: replan from the next frame with fresh noise
                policy.reset()
                preprocessor.reset()
                postprocessor.reset()
        elif policy is not None and preprocessor is not None and postprocessor is not None:
            if guard is not None and guard.mode == "learned":  # [eval] StallGuard learned: plan with "back" for a while
                cmd = guard.command()
                if cmd != policy.diffusion.adv_command:  # switch: replan at once with the new indicator
                    policy.diffusion.adv_command = cmd
                    policy.reset()
                    preprocessor.reset()
                    postprocessor.reset()
            policy_obs = clip_state(observation_frame, state_range)
            if stage is not None:
                policy_obs = {**policy_obs, OBS_ENV_STATE: stage_now}
            action_values = predict_action(
                observation=policy_obs,
                policy=policy,
                device=get_safe_torch_device(policy.config.device),
                preprocessor=preprocessor,
                postprocessor=postprocessor,
                use_amp=policy.config.use_amp,
                task=single_task,
                robot_type=robot.robot_type,
            )

            act_processed_policy: RobotAction = make_robot_action(action_values, dataset.features)
            extra = action_values.reshape(-1)[len(dataset.features[ACTION]["names"]):]
            head = getattr(getattr(policy, "diffusion", None), "stage_head_pred", None)
            if memory:  # [eval] progress feedback: s is updated after the chunk's last action (ProgressMemory)
                pred_now, prog_now = stage.update(policy, timestamp)
                if prog_now >= 0.97:  # [eval] whole task 97% (stage 9/9) -> same as pressing Right arrow: end trial, arms reset
                    events["exit_early"] = True
            elif head is not None:  # [eval] stagehead: its own stage guess (updated once per chunk) vs the rule's input
                pred = int(head[0].argmax())
                pred_now, prob_now = pred, float(head[0, pred])
                if pred != pred_stage:
                    print(f"[head]  {timestamp:6.2f}s  {pred}  p={float(head[0, pred]):.2f}", flush=True)
                pred_stage = pred
            elif getattr(policy.config, "progress_pred_dims", 0):  # [eval] v9: the chunk's own predicted s at this action
                v = float(np.clip(extra, 0.0, 1.0).sum())
                pred_now, prog_now = min(int(v), len(extra) - 1), v / len(extra)
                if int(v * 10) != pred_stage:  # printed per 0.1 stage
                    print(f"[v9]    {timestamp:6.2f}s  progress {v:.2f} / {len(extra)}", flush=True)
                pred_stage = int(v * 10)
            elif len(extra) == 9:  # [eval] *-stagepred: the predicted stage one-hot after the joints, printed as 0-8 on change
                pred = int(extra.argmax())
                pred_now, prob_now = pred, float(extra[pred])
                if pred != pred_stage:
                    print(f"[pred]  {timestamp:6.2f}s  {pred}", flush=True)
                pred_stage = pred
            elif len(extra) == 1:  # [eval] *-progpred: predicted progress 0..1 -> stage 0-8 + % through it, printed per 10%
                if str(XLEROBOT) not in sys.path:
                    sys.path.insert(0, str(XLEROBOT))
                from stage_labels import PROG_SHARES, PROG_STARTS  # share of 0..1 progress per fine9 stage

                p = float(extra[0])
                k = min(max(int(np.searchsorted(PROG_STARTS, p, side="right")) - 1, 0), len(PROG_SHARES) - 1)
                pct = min(max((p - PROG_STARTS[k]) / PROG_SHARES[k], 0.0), 1.0)
                pred = (k, int(pct * 10))
                pred_now, prog_now = k, p
                if pred != pred_stage:
                    print(f"[prog]  {timestamp:6.2f}s  {p:.2f}  stage {k} {pct:4.0%}", flush=True)
                pred_stage = pred

        elif policy is None and isinstance(teleop, Teleoperator):
            act = teleop.get_action()
            if not act:
                time.sleep(0.01)
                continue
            # Applies a pipeline to the raw teleop action, default is IdentityProcessor
            act_processed_teleop = teleop_action_processor((act, obs))

        elif policy is None and isinstance(teleop, list):
            arm_action = teleop_arm.get_action()
            arm_action = {f"arm_{k}": v for k, v in arm_action.items()}
            keyboard_action = teleop_keyboard.get_action()
            base_action = robot._from_keyboard_to_base_action(keyboard_action)
            act = {**arm_action, **base_action} if len(base_action) > 0 else arm_action
            act_processed_teleop = teleop_action_processor((act, obs))
        else:
            logging.info(
                "No policy or teleoperator provided, skipping action generation."
                "This is likely to happen when resetting the environment without a teleop device."
                "The robot won't be at its rest position at the start of the next episode."
            )
            continue

        # Applies a pipeline to the action, default is IdentityProcessor
        if policy is not None and act_processed_policy is not None:
            action_values = act_processed_policy
            robot_action_to_send = robot_action_processor((act_processed_policy, obs))
        else:
            action_values = act_processed_teleop
            robot_action_to_send = robot_action_processor((act_processed_teleop, obs))

        # Send action to robot
        # Action can eventually be clipped using `max_relative_target`,
        # so action actually sent is saved in the dataset. action = postprocessor.process(action)
        # TODO(steven, pepijn, adil): we should use a pipeline step to clip the action, so the sent action is the action that we input to the robot.
        if policy is not None and max_arm_step > 0:
            prev = prev_sent if prev_sent is not None else obs
            # Leader commands get only the EMA + step limit, like the recording script (no 3-tap filter),
            # and leader grippers none: the operator's grip must act at once.
            grips = {k: v for k, v in robot_action_to_send.items() if human and "gripper" in k}
            robot_action_to_send, raw_hist = smooth_arm_action(
                robot_action_to_send, [] if human else raw_hist, prev, max_arm_step
            )
            robot_action_to_send.update(grips)
            if blend_from is not None:  # smoothstep from the switch command to the new source over 1 s
                blend_frames += 1
                x = min(1.0, blend_frames / fps)
                a = x * x * (3 - 2 * x)
                for k, v0 in blend_from.items():
                    if k in robot_action_to_send:
                        robot_action_to_send[k] = v0 + a * (float(robot_action_to_send[k]) - v0)
                if x >= 1.0:
                    blend_from = None
            prev_sent = dict(robot_action_to_send)

        if policy is not None and not allow_base:
            robot_action_to_send.update({k: 0.0 for k in BASE_STOP if k in robot.action_features})

        sent_action = robot.send_action(robot_action_to_send)
        last_cmd = dict(sent_action if sent_action is not None else robot_action_to_send)
        if guard is not None and not human:
            guard.observe(np.array([float(obs[k]) for k in guard_keys]), last_cmd, prog_now)
            frame_no = dataset.episode_buffer["size"] if dataset is not None else len(guard.states)
            if guard.check(frame_no) and guard.mode == "resample":
                policy.reset()
                preprocessor.reset()
                postprocessor.reset()

        # Write to dataset
        if dataset is not None:
            action_frame = build_dataset_frame(
                dataset.features, sent_action if sent_action is not None else robot_action_to_send, prefix=ACTION
            )
            frame = {**observation_frame, **action_frame, "task": single_task}
            if policy is not None:  # kept only if it has a stage (save_stage_log)
                log.append([dataset.episode_buffer["size"], -1 if stage_now is None or memory else int(stage_now.argmax()),
                            pred_now, prob_now, prog_now])
            dataset.add_frame(frame)

        if display_data:
            log_rerun_data(observation=obs_processed, action=action_values)

        dt_s = time.perf_counter() - start_loop_t
        precise_sleep(1 / fps - dt_s)

        timestamp = time.perf_counter() - start_episode_t

    if human:
        spans[-1][1] = dataset.episode_buffer["size"] if dataset is not None else 0
    if homing is not None:
        homing.join()
    return [tuple(s) for s in spans]


