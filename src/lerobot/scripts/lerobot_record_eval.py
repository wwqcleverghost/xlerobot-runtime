def live_stage(policy):
    """stage_labels.LiveStage when the policy takes observation.environment_state (trained on a *-stagelabel dataset),
    ProgressMemory when that input is the policy's own progress (config.progress_mode), else None.
    LiveStage needs the wrist cameras 'left_wrist' / 'right_wrist' in the robot observation."""
    if policy is None or OBS_ENV_STATE not in (getattr(policy.config, "input_features", None) or {}):
        return None
    if getattr(policy.config, "progress_mode", None):
        print(f"Progress memory on: {OBS_ENV_STATE} = the model's own stage progress ({policy.config.progress_mode}), starts at 0")
        mem = ProgressMemory(policy)
        if os.environ.get("PROGRESS_S2"):  # [s2] head | path of a separate estimator (v6-progcheck_mix*)
            mem.attach_check(policy, os.environ["PROGRESS_S2"])
        return mem
    if str(XLEROBOT) not in sys.path:
        sys.path.insert(0, str(XLEROBOT))
    from stage_labels import STAGES, LiveStage

    shape = policy.config.input_features[OBS_ENV_STATE].shape
    assert tuple(shape) == (len(STAGES),), f"{OBS_ENV_STATE} has shape {shape}, stage labels have {len(STAGES)}"
    print(f"Stage input on: {OBS_ENV_STATE} = live fine9 stage ({len(STAGES)} one-hot, docs/workflows/stage-labels)")
    return LiveStage()


def train_state_range(preprocessor) -> tuple[np.ndarray, np.ndarray] | None:
    """[eval] Training min/max of observation.state, from the policy's normalizer step."""
    for step in getattr(preprocessor, "steps", []):
        stats = (getattr(step, "stats", None) or {}).get(OBS_STATE, {})
        if "min" in stats and "max" in stats:
            return np.asarray(stats["min"], dtype=np.float32), np.asarray(stats["max"], dtype=np.float32)
    return None


def clip_state(observation_frame: dict, state_range) -> dict:
    """[eval] The policy sees the state clipped into its training range; the dataset keeps the measured one.
    The head servos barely moved while recording (0.1-0.4 deg range), so being 1 deg off normalizes to 3-5
    instead of [-1, 1] and the policy drives both arms to the same pose whatever the camera shows."""
    if state_range is None or OBS_STATE not in observation_frame:
        return observation_frame
    return {**observation_frame, OBS_STATE: np.clip(observation_frame[OBS_STATE], *state_range).astype(np.float32)}


def smooth_arm_action(action: dict, raw_hist: list, prev: dict, max_arm_step: float) -> tuple[dict, list]:
    """[eval] A [1, 2, 1] / 4 filter over the last three policy outputs cancels the frame-to-frame zig-zag of
    Diffusion/flow samples (1 frame lag); then each joint position moves 0.8 of the way from the previous
    command `prev` (first frame: measured pose), at most `max_arm_step` per frame. Returns (action, raw_hist)."""
    raw = dict(action)
    a2, a1 = (raw_hist or [raw, raw])[-2:]
    out = dict(action)
    for k, v in raw.items():
        if k.endswith(".pos") and k in prev:
            v = (float(v) + 2 * float(a1[k]) + float(a2[k])) / 4
            p = float(prev[k])
            out[k] = p + max(-max_arm_step, min(max_arm_step, 0.8 * (v - p)))
    return out, [a1, raw]


def init_eval_keyboard_listener():
    """Only accept episode arrow keys while recording; Esc always requests a stop."""
    events = {
        "exit_early": False,
        "rerecord_episode": False,
        "stop_recording": False,
        "recording_active": False,
        "takeover": False,
    }
    if is_headless():
        return None, events

    from pynput import keyboard

    def on_press(key):
        if key == keyboard.Key.esc:
            events["stop_recording"] = True
            events["exit_early"] = True
        elif events["recording_active"]:
            if key == keyboard.Key.right:
                events["exit_early"] = True
            elif key == keyboard.Key.left:
                events["rerecord_episode"] = True
                events["exit_early"] = True
            elif key == keyboard.Key.space:
                events["takeover"] = not events["takeover"]

    listener = keyboard.Listener(on_press=on_press)
    listener.start()
    return listener, events


