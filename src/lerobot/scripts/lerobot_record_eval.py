def save_stage_log(root: Path, episode_index: int, log: list) -> None:
    """[eval] Append the per-frame stages of a saved episode to stages.csv (docs/workflows/dataset-viewer "阶段 / 进度"):
    rule = the live fine9 stage fed to the model (-1: no stage input), pred = the model's own stage guess (stage head,
    *-stagepred argmax, *-progpred progress -> stage; -1 on human frames or none), prob = its probability (stage head
    softmax / stagepred output), progress = the *-progpred output 0..1 (empty when not given). Progress feedback models
    (ProgressMemory): rule -1, pred = stage of their own s, progress = sum(s) / 9."""
    if not any(r[1] >= 0 or r[2] >= 0 for r in log):  # a plain model: nothing to save
        return
    csv_path = Path(root) / "stages.csv"
    new_file = not csv_path.exists()
    with csv_path.open("a", newline="") as f:
        writer = csv.writer(f)
        if new_file:
            writer.writerow(["episode", "frame", "rule", "pred", "prob", "progress"])
        writer.writerows([episode_index, *r[:3], *("" if v != v else round(v, 4) for v in r[3:])] for r in log)


@parser.wrap()
def record(cfg: RecordConfig) -> LeRobotDataset:
    init_logging()
    logging.info(pformat(asdict(cfg)))
    if cfg.display_data:
        init_rerun(session_name="recording")

    if cfg.takeover and (cfg.policy is None or cfg.teleop is None):
        raise ValueError("--takeover needs both --policy.path and a leader --teleop")
    robot = make_robot_from_config(cfg.robot)
    teleop = make_teleoperator_from_config(cfg.teleop) if cfg.teleop is not None else None

    teleop_action_processor, robot_action_processor, robot_observation_processor = make_default_processors()

    dataset_features = combine_feature_dicts(
        aggregate_pipeline_dataset_features(
            pipeline=teleop_action_processor,
            initial_features=create_initial_features(
                action=robot.action_features
            ),  # TODO(steven, pepijn): in future this should be come from teleop or policy
            use_videos=cfg.dataset.video,
        ),
        aggregate_pipeline_dataset_features(
            pipeline=robot_observation_processor,
            initial_features=create_initial_features(observation=robot.observation_features),
            use_videos=cfg.dataset.video,
        ),
    )
    # [eval] Leave out the state/action entries the policy was trained without (e.g. the head servos): the
    # recorded dataset matches the policy, and the robot gets no command for them.
    train_cfg_path = None if cfg.policy is None else Path(cfg.policy.pretrained_path) / "train_config.json"
    if train_cfg_path is not None and train_cfg_path.is_file():
        drop_feature_names(dataset_features, json.loads(train_cfg_path.read_text())["dataset"].get("drop_names", []))
        # Datasets already recorded without the head/base (e.g. *-stagelabel) don't list them in drop_names.
        if len(dataset_features[ACTION]["names"]) != cfg.policy.output_features[ACTION].shape[0]:
            drop_feature_names(dataset_features, ["head_motor_1.pos", "head_motor_2.pos", *BASE_STOP])

    dataset = None
    listener = None

    try:
        if cfg.resume:
            dataset = LeRobotDataset(
                cfg.dataset.repo_id,
                root=cfg.dataset.root,
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
            )

            if len(getattr(robot, "cameras", None) or robot.config.cameras) > 0:
                dataset.start_image_writer(
                    num_processes=cfg.dataset.num_image_writer_processes,
                    num_threads=cfg.dataset.num_image_writer_threads_per_camera * len(getattr(robot, "cameras", None) or robot.config.cameras),
                )
            sanity_check_dataset_robot_compatibility(dataset, robot, cfg.dataset.fps, dataset_features)
            dataset.episode_buffer = dataset.create_episode_buffer()
        else:
            # Create empty dataset or load existing saved episodes
            sanity_check_dataset_name(cfg.dataset.repo_id, cfg.policy)
            dataset = LeRobotDataset.create(
                cfg.dataset.repo_id,
                cfg.dataset.fps,
                root=cfg.dataset.root,
                robot_type=robot.name,
                features=dataset_features,
                use_videos=cfg.dataset.video,
                image_writer_processes=cfg.dataset.num_image_writer_processes,
                image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * len(getattr(robot, "cameras", None) or robot.config.cameras),
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
            )

        # Preserve observation aliases saved with the checkpoint (needed by SmolVLA).
        if cfg.policy is not None and not cfg.dataset.rename_map:
            processor_path = Path(cfg.policy.pretrained_path) / "policy_preprocessor.json"
            if processor_path.is_file():
                saved_steps = json.loads(processor_path.read_text())["steps"]
                cfg.dataset.rename_map = next(
                    (step["config"].get("rename_map", {}) for step in saved_steps
                     if step["registry_name"] == "rename_observations_processor"),
                    {},
                )

        # Load pretrained policy
        # [eval] Build the net with the trained action size: *-stagepred / -progpred predict extra targets after the joints,
        # which make_robot_action drops (it maps the first len(names) outputs to the robot's joint names).
        policy_meta = dataset.meta
        if cfg.policy is not None and tuple(dataset.features[ACTION]["shape"]) != tuple(cfg.policy.output_features[ACTION].shape):
            policy_meta = copy.copy(dataset.meta)
            act = {**dataset.meta.features[ACTION], "shape": tuple(cfg.policy.output_features[ACTION].shape)}
            policy_meta.info = {**dataset.meta.info, "features": {**dataset.meta.features, ACTION: act}}
        policy = None if cfg.policy is None else make_policy(cfg.policy, ds_meta=policy_meta, rename_map=cfg.dataset.rename_map)  # [eval] official omits rename_map
        preprocessor = None
        postprocessor = None
        if cfg.policy is not None:
            preprocessor, postprocessor = make_pre_post_processors(
                policy_cfg=cfg.policy,
                pretrained_path=cfg.policy.pretrained_path,
                dataset_stats=rename_stats(dataset.meta.stats, cfg.dataset.rename_map),
                preprocessor_overrides={
                    "device_processor": {"device": cfg.policy.device},
                    "rename_observations_processor": {"rename_map": cfg.dataset.rename_map},
                },
            )

        robot.connect()
        if teleop is not None:
            teleop.connect()

        listener, events = init_eval_keyboard_listener()
        if listener is None:
            raise RuntimeError("Evaluation requires a desktop keyboard listener; run from a desktop terminal")

        # [eval] Auto arm reset + success prompt when a policy runs without a teleoperator.
        auto_reset = policy is not None and (teleop is None or cfg.takeover)
        results = load_success_history(Path(dataset.root) / "success.csv", dataset.num_episodes)
        if results:
            print(f"Saved success rate: {sum(results)}/{len(results)} = {sum(results) / len(results):.0%}")
        if auto_reset:
            reset_repo = cfg.reset_dataset or json.loads(
                (Path(cfg.policy.pretrained_path) / "train_config.json").read_text()
            )["dataset"]["repo_id"]
            reset_pose = dataset_start_pose(reset_repo)

            def reset_both():
                """Follower and (with --takeover) leader go to the rest pose at the same time."""
                leader = None
                if cfg.takeover:
                    kw = {"speed": cfg.reset_speed, "show": False}
                    leader = threading.Thread(target=align_leader, args=(teleop, reset_pose, cfg.dataset.fps), kwargs=kw)
                    leader.start()
                reset_arms(robot, reset_pose, cfg.dataset.fps, cfg.reset_speed)
                if leader is not None:
                    leader.join()

            reset_both()
            flush_stdin()
            input(
                f"Place the object, then press Enter to start trial {dataset.num_episodes + 1} "
                f"of {cfg.dataset.num_episodes}: "
            )
            events["exit_early"] = False

        with VideoEncodingManager(dataset):
            recorded_episodes = dataset.num_episodes
            while recorded_episodes < cfg.dataset.num_episodes and not events["stop_recording"]:
                log_say(f"Recording trial {dataset.num_episodes + 1} of {cfg.dataset.num_episodes}", cfg.play_sounds)
                events["exit_early"] = False
                events["rerecord_episode"] = False
                events["recording_active"] = True
                try:
                    spans = record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop_action_processor=teleop_action_processor,
                        robot_action_processor=robot_action_processor,
                        robot_observation_processor=robot_observation_processor,
                        teleop=teleop,
                        policy=policy,
                        preprocessor=preprocessor,
                        postprocessor=postprocessor,
                        dataset=dataset,
                        control_time_s=cfg.dataset.episode_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                        max_arm_step=cfg.max_arm_step,
                        allow_base=cfg.allow_base,
                        takeover=cfg.takeover,
                        leader_rest=reset_pose if cfg.takeover else None,
                    )
                finally:
                    events["recording_active"] = False

                if events["stop_recording"]:
                    break
                if not dataset.episode_buffer or dataset.episode_buffer["size"] == 0:
                    logging.warning("No frames recorded; this trial will not be saved or counted")
                    dataset.episode_buffer = dataset.create_episode_buffer()
                    flush_stdin()
                    input("Place the object, then press Enter to retry this trial: ")
                    continue

                if auto_reset:
                    # [eval] Replace the idle reset loop: move arms back, ask for success, start next episode.
                    log_say("Reset the environment", cfg.play_sounds)
                    reset_both()
                    if events["stop_recording"]:
                        break
                    if events["rerecord_episode"]:
                        log_say("Re-record episode", cfg.play_sounds)
                        events["rerecord_episode"] = False
                        dataset.clear_episode_buffer()
                        flush_stdin()
                        input("Put the object back, then press Enter to re-run the episode: ")
                        events["exit_early"] = False
                        continue
                    success = ask_success()
                    events["exit_early"] = False  # ignore -> presses made while answering
                    episode_index = dataset.num_episodes
                    save_evaluation_episode(dataset, success, cfg.policy.pretrained_path)
                    save_interventions(dataset.root, episode_index, spans)
                    save_stage_log(dataset.root, episode_index, events.pop("stage_log", []))
                    save_stall_log(dataset.root, episode_index, events.pop("stall_log", []))
                    results.append(success)
                    print(f"Success rate: {sum(results)}/{len(results)} = {sum(results) / len(results):.0%}")
                    recorded_episodes += 1
                    continue

                # Execute a few seconds without recording to give time to manually reset the environment
                # Skip reset for the last episode to be recorded
                if not events["stop_recording"] and (
                    (recorded_episodes < cfg.dataset.num_episodes - 1) or events["rerecord_episode"]
                ):
                    log_say("Reset the environment", cfg.play_sounds)
                    record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop_action_processor=teleop_action_processor,
                        robot_action_processor=robot_action_processor,
                        robot_observation_processor=robot_observation_processor,
                        teleop=teleop,
                        control_time_s=cfg.dataset.reset_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                    )

                if events["rerecord_episode"]:
                    log_say("Re-record episode", cfg.play_sounds)
                    events["rerecord_episode"] = False
                    events["exit_early"] = False
                    dataset.clear_episode_buffer()
                    continue
                dataset.save_episode()
                recorded_episodes += 1
    finally:
        log_say("Stop recording", cfg.play_sounds, blocking=True)

        if dataset:
            dataset.finalize()

        if robot.is_connected:
            robot.disconnect()
        if teleop and teleop.is_connected:
            teleop.disconnect()

        if not is_headless() and listener:
            listener.stop()

        if cfg.dataset.push_to_hub:
            dataset.push_to_hub(tags=cfg.dataset.tags, private=cfg.dataset.private)

        log_say("Exiting", cfg.play_sounds)
    return dataset


def main():
    register_third_party_plugins()
    record()


if __name__ == "__main__":
    main()
